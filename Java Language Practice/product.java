import java.util.*;
public class product {
    
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int a = sc.nextInt(); //nextInt() method is used to read an integer value from the user input
        int b = sc.nextInt(); //nextInt() method is used to read an integer value from the user input
        int product = a * b; //product of two integers
        System.out.println("Product of two integers: " + product); //print the product of two integers
    }
}