import java.util.*;
public class sum {
    
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int a = sc.nextInt(); //nextInt() method is used to read an integer value from the user input
        int b = sc.nextInt(); //nextInt() method is used to read an integer value from the user input
        int sum = a + b; //sum of two integers
        System.out.println("Sum of two integers: " + sum); //print the sum of two integers
    }
}